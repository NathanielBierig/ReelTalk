// Inlines the Vite build (dist/) into worker/assets.gen.ts.
// Why: the cloud session's credential proxy breaks Wrangler's static-asset upload,
// so the frontend ships inside the Worker script instead. Fine for a small SPA.
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs'
import { join, relative, extname } from 'node:path'

const DIST = new URL('../dist/', import.meta.url).pathname
const OUT = new URL('../worker/assets.gen.ts', import.meta.url).pathname
const TYPES = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8', '.svg': 'image/svg+xml', '.json': 'application/json',
  '.png': 'image/png', '.jpg': 'image/jpeg', '.ico': 'image/x-icon', '.woff2': 'font/woff2',
  '.webmanifest': 'application/manifest+json', '.txt': 'text/plain',
}
const TEXT = new Set(['.html', '.js', '.css', '.svg', '.json', '.webmanifest', '.txt'])
const out = {}
function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f)
    if (statSync(p).isDirectory()) { walk(p); continue }
    const ext = extname(p)
    const key = '/' + relative(DIST, p).split('\\').join('/')
    const text = TEXT.has(ext)
    out[key] = { type: TYPES[ext] ?? 'application/octet-stream', b64: !text, body: readFileSync(p, text ? 'utf8' : 'base64') }
  }
}
if (existsSync(DIST)) walk(DIST)
writeFileSync(OUT, `// Generated by scripts/bundle-assets.mjs. Do not edit.\nexport const ASSETS: Record<string, { type: string; b64: boolean; body: string }> = ${JSON.stringify(out)}\n`)
console.log(`bundled ${Object.keys(out).length} files into worker/assets.gen.ts`)
